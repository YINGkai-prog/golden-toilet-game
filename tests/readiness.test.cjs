'use strict';
const {test}=require('node:test'),assert=require('node:assert/strict');
const {start,KEY,delay}=require('./helpers.cjs');
test('100 simultaneous entrants reserve only 50 seats; reconnects keep identity and votes even when full',{timeout:90000},async t=>{
 const app=await start();t.after(()=>app.stop());const host=await app.connect({host:true,key:KEY});
 host.send({t:'h.openLobby'});await delay(3500);
 const peers=await Promise.all(Array.from({length:100},()=>app.connect({stateDelta:1})));
 peers.forEach((p,i)=>p.send({t:'join',name:'驗收'+i}));
 const replies=await Promise.all(peers.map(p=>p.wait(m=>m.t==='you'||m.t==='err')));
 const accepted=replies.map((m,i)=>({m,p:peers[i]})).filter(x=>x.m.t==='you');
 assert.equal(accepted.length,50);assert.equal(replies.filter(m=>m.code==='full').length,50);
 const observer=await app.connect(),s=observer.welcome.s;assert.equal(s.players.length,50);
 const q=accepted.find(x=>x.m.you.id===s.board.members[1]),player=q.m.you;
 q.p.send({t:'board.vote',candidate:s.board.members[0],round:s.board.round});
 await host.wait(m=>m.t==='state'&&m.s.board.votes[player.id]);q.p.close();
 const restored=await app.connect({token:player.token});assert.equal(restored.welcome.you.id,player.id);
 assert.equal(restored.welcome.s.board.votes[player.id],s.board.members[0]);
 assert.deepEqual(restored.welcome.s.players.find(p=>p.id===player.id).appearance,s.players.find(p=>p.id===player.id).appearance);
 assert.equal(restored.welcome.s.players.length,50);
 restored.send({t:'join',name:'不能變成另一個人'});assert.equal((await restored.wait('you')).you.id,player.id);
 const forged=await app.connect({token:'invalid-token'});assert.equal(forged.welcome.you,null);
 forged.send({t:'join',name:'無效續玩'});assert.equal((await forged.wait('err')).code,'full');
 const w=await fetch(app.base+'/api/watch').then(r=>r.json());assert.equal(w.players,50);assert.equal(w.available,0);
 assert.equal(w.canJoin,false);assert.equal(w.teams.length,3);assert.ok(!JSON.stringify(w).includes(player.token));assert.ok(!('builds' in w));
 host.send({t:'h.kick',id:player.id});await delay(1300);
 const vacant=await fetch(app.base+'/api/watch').then(r=>r.json());assert.equal(vacant.available,1);assert.equal(vacant.canJoin,true);
 const kicked=await app.connect({token:player.token});assert.equal(kicked.welcome.you,null);
 forged.send({t:'join',name:'候補同仁'});assert.ok((await forged.wait('you')).you.id);
 assert.equal((await app.connect()).welcome.s.players.length,50);
});
test('HTTP fallback resumes an existing seat and AI hands control back after inactivity',{timeout:90000},async t=>{
 const app=await start();t.after(()=>app.stop());const host=await app.connect({host:true,key:KEY});host.send({t:'h.openLobby'});await delay(3500);
 const p=await app.connect();p.send({t:'join',name:'離開再回來'});const you=(await p.wait('you')).you;p.idle();p.close();
 await delay(31000);assert.equal((await app.connect()).welcome.s.players.find(p=>p.id===you.id).aiControlled,true);
 const {cid}=await fetch(app.base+'/rt/connect',{method:'POST'}).then(r=>r.json());
 const send=messages=>fetch(app.base+'/rt/send?cid='+cid,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(messages)});
 await send([{t:'hello',token:you.token,stateDelta:1}]);const messages=await fetch(app.base+'/rt/poll?cid='+cid).then(r=>r.json());
 const welcome=messages.find(m=>m.t==='welcome');assert.equal(welcome.you.id,you.id);assert.equal(welcome.s.players.length,1);
 await send([{t:'input.active'}]);await host.wait(m=>m.t==='state'&&m.s.players.find(p=>p.id===you.id)?.aiControlled===false);
 assert.equal((await app.connect()).welcome.s.players[0].id,you.id);
});
